/**
 * Text as a regular expression matches it, each character a pattern reads as an operator escaped:
 * for the marks the server and the pages draw alike (a canary's every form, a field's name in a
 * refusal). No imports: the pages' bundle imports this too.
 */
export const literal = (s: string): string => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
